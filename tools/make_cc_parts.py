# Camera Check pieces for the touch screen version of it (bottom_ui.c, camera_check.cpp,
# n64_renderer.cpp), cut from the game's own art in a full snapshot taken in Camera Check
# (snapshots_full.txt: snap_<vi>.bin RAM and snap_<vi>/tex_<addr>_<w>x<h>_*.rgba textures):
#   gfx/cc_tile.png               the screen's teal background tile (16x16, sprite 0x801FCC58)
#   gfx/cc_btn_oak/album/send.png the menu's "Oak's Mark", "Album Mark", "To Prof. Oak" buttons (92x21)
#   gfx/cc_mark_oak/album.png     the grid's small marks (12x12, sprites 0x801FFC88 / 0x801FFB08)
#   gfx/cc_new.png                the grid's NEW ribbon (7x28, sprite 0x801FCE78)
#   gfx/cc_knob_l/r.png           the orange page knobs (24x39)
#   source/render/cc_parts_rgba.h the top screen's: the tile, the big view's marks (32x32, 0x801FF988
#                                 Oak, 0x801FF128 album) and its NEW badge (26x13 in 32x16, 0x801FD9E0)
# Sprites are read from RAM: Sprite { width +4, height +6, nbitmaps +0x28, bmsiz +0x31, bitmap +0x34 },
# Bitmap (0x10 each) { width +0, width_img +2, buf +8, actualHeight +0xC }, RGBA5551 texels with every
# odd row's 32-bit words swapped (address XOR 4), as the game keeps them for TMEM.
# Usage: python -I tools/make_cc_parts.py <snapshot dir, e.g. tools/tmp/cc/snap_16400>
import glob
import struct
import sys

from PIL import Image

ROOT = __file__.replace("\\", "/").rsplit("/tools/", 1)[0]
snap = sys.argv[1].rstrip("/\\")
ram = open(snap + ".bin", "rb").read()


def u32(a):
    return struct.unpack_from("<I", ram, a & 0xFFFFFC)[0]


def s16(a):
    a &= 0xFFFFFF
    return struct.unpack_from("<h", ram, (a & ~3) + (2 - (a & 2)))[0]


def u8(a):
    return ram[(a & 0xFFFFFF) ^ 3]


def sprite(addr):
    w, h = s16(addr + 4), s16(addr + 6)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    y, b = 0, u32(addr + 0x34)
    for _ in range(s16(addr + 0x28)):
        wimg, buf, actual = s16(b + 2), u32(b + 8), s16(b + 0xC)
        for r in range(actual):
            for x in range(w):
                a = buf + (r * wimg + x) * 2
                if r & 1:
                    a ^= 4
                v = (u8(a) << 8) | u8(a + 1)
                c = lambda s: (v >> s & 31) * 255 // 31
                if y + r < h:
                    img.putpixel((x, y + r), (c(11), c(6), c(1), 255 if v & 1 else 0) if v & 1 else (0, 0, 0, 0))
        y += actual
        b += 0x10
    return img


def texture(addr, w, h):
    data = open(glob.glob(f"{snap}/tex_{addr}_{w}x{h}_*.rgba")[0], "rb").read()
    return Image.frombytes("RGBA", (w, h), data[: w * h * 4])


def write_header(path, images):
    lines = ["// Generated by tools/make_cc_parts.py from the game's Camera Check art: RGBA8 (0xRRGGBBAA),",
             "// rows top to bottom.", "#pragma once", "#include <cstdint>", ""]
    for name, im in images:
        w, h = im.size
        px = im.load()
        lines.append(f"constexpr int {name}_w = {w}, {name}_h = {h};")
        lines.append(f"static const uint32_t {name}_rgba[{name}_w * {name}_h] = {{")
        for y in range(h):
            row = []
            for x in range(w):
                r, g, b, a = px[x, y]
                row.append("0x%02X%02X%02X%02Xu" % ((r, g, b, a) if a else (0, 0, 0, 0)))
            lines.append("    " + ",".join(row) + ",")
        lines.append("};")
        lines.append("")
    open(path, "w").write("\n".join(lines))


def padded(im, w, h):
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    out.paste(im, (0, 0))
    return out


tile = sprite(0x801FCC58)
gfx = ROOT + "/gfx/"
tile.save(gfx + "cc_tile.png")
texture("3979F0", 92, 21).save(gfx + "cc_btn_oak.png")
texture("398910", 92, 21).save(gfx + "cc_btn_album.png")
texture("396AD0", 92, 21).save(gfx + "cc_btn_send.png")
sprite(0x801FFC88).save(gfx + "cc_mark_oak.png")
sprite(0x801FFB08).save(gfx + "cc_mark_album.png")
sprite(0x801FCE78).save(gfx + "cc_new.png")
texture("3A13B0", 24, 39).save(gfx + "cc_knob_l.png")
texture("3A1B60", 24, 39).save(gfx + "cc_knob_r.png")
write_header(ROOT + "/source/render/cc_parts_rgba.h", [
    ("cc_tile", tile),
    ("cc_oak", sprite(0x801FF988)),
    ("cc_album", sprite(0x801FF128)),
    ("cc_new", padded(sprite(0x801FD9E0), 32, 16)),
])
print("ok")
