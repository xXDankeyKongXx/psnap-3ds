# Textures for the port's own "DANKEY KONG" credits (n64_renderer.cpp):
#   source/render/dankey_logo_rgba.h       512x64  the logo (art/dankey_kong.png), shown in the intro
#                                                  after JACK and BEANS, with its fade
#   source/render/dankey_copyright_rgba.h  64x16   "Dankey Kong 2026" in the title screen's copyright
#                                                  font, put after "HAL Laboratory,Inc."
# The copyright font is the game's own 7-pixel one (white, 1-pixel black outline): the glyphs below
# are copied from the title screen's two copyright lines (a, n, e, o, y, K, 6) or drawn to match
# (D, k, g, 0, 2).
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Rows y = 210..216 of the title screen ('#' white).
GLYPHS = {
    "D": ["##.", "#.#", "#.#", "#.#", "#.#", "#.#", "##."],
    "a": ["...", "...", "###", "..#", "###", "#.#", "###"],
    "n": ["...", "...", "##.", "#.#", "#.#", "#.#", "#.#"],
    "k": ["#..", "#..", "#.#", "#.#", "##.", "#.#", "#.#"],
    "e": ["...", "...", "###", "#.#", "###", "#..", "###"],
    "y": ["...", "...", "#.#", "#.#", ".#.", ".#.", "#.."],
    "K": ["#.#", "#.#", "#.#", "##.", "#.#", "#.#", "#.#"],
    "o": ["...", "...", "###", "#.#", "#.#", "#.#", "###"],
    "g": ["...", "...", "###", "#.#", "###", "..#", "##."],
    "2": ["###", "..#", "..#", "###", "#..", "#..", "###"],
    "0": ["###", "#.#", "#.#", "#.#", "#.#", "#.#", "###"],
    "6": [".##", "#..", "#..", "###", "#.#", "#.#", "###"],
}
TEXT = "Dankey Kong 2026"
SPACE = 4  # columns between words (as between "1999" and "Nintendo")


def write_header(path, name, im):
    w, h = im.size
    px = im.load()
    lines = [f"// Generated by tools/make_dankey_assets.py: {w}x{h} RGBA8 (0xRRGGBBAA), rows top to bottom.",
             "#pragma once", "#include <cstdint>", "",
             f"constexpr int {name}_w = {w}, {name}_h = {h};",
             f"static const uint32_t {name}_rgba[{name}_w * {name}_h] = {{"]
    for y in range(h):
        row = []
        for x in range(w):
            r, g, b, a = px[x, y]
            if a == 0:
                r = g = b = 0
            row.append("0x%02X%02X%02X%02Xu" % (r, g, b, a))
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def copyright_text():
    # White glyph pixels from x = 1, y = 1 (a column and row of outline before them).
    white = set()
    x = 1
    for ch in TEXT:
        if ch == " ":
            x += SPACE - 1
            continue
        g = GLYPHS[ch]
        for gy, row in enumerate(g):
            for gx, c in enumerate(row):
                if c == "#":
                    white.add((x + gx, 1 + gy))
        x += len(g[0]) + 1
    im = Image.new("RGBA", (64, 16), (0, 0, 0, 0))
    for (wx, wy) in white:
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                p = (wx + dx, wy + dy)
                if p not in white and 0 <= p[0] < 64 and 0 <= p[1] < 16:
                    im.putpixel(p, (0, 0, 0, 255))
    for p in white:
        im.putpixel(p, (255, 255, 255, 255))
    print("copyright text: %d columns" % (max(p[0] for p in white) + 2))
    return im


def logo():
    art = Image.open(os.path.join(ROOT, "art/dankey_kong.png")).convert("RGBA")
    h = 64
    w = round(art.width * h / art.height)
    if w > 512:
        w, h = 512, round(art.height * 512 / art.width)
    art = art.resize((w, h), Image.LANCZOS)
    im = Image.new("RGBA", (512, 64), (0, 0, 0, 0))
    im.alpha_composite(art, ((512 - w) // 2, (64 - h) // 2))
    print("logo %dx%d in 512x64" % (w, h))
    return im


def main():
    write_header(os.path.join(ROOT, "source/render/dankey_logo_rgba.h"), "dankey_logo", logo())
    text = copyright_text()
    text.save(os.path.join(ROOT, "tools/tmp/dankey_copyright.png"))
    write_header(os.path.join(ROOT, "source/render/dankey_copyright_rgba.h"), "dankey_copyright", text)


if __name__ == "__main__":
    main()
