# Builds gfx/font.png, the game's 12x12 UI font (window overlay, window/text.c) as an atlas for the
# bottom screen: printable ASCII 32-127 in a 16x6 grid of 12x12 cells, white, alpha from the glyph's
# 4-bit value. The glyphs are read from a RAM snapshot taken while the window overlay is loaded (e.g.
# in Oak's Lab): D_8037EA68 holds the 8x8 and 12x12 glyph data pointers; glyph i of UIText_CharTable
# is 72 bytes (12x12, 4 bits per pixel, even pixels in the low nibble). Latin letters, digits and
# punctuation are the table's full-width characters.
# Usage: python -I tools/make_font.py <lab ram snapshot>
import re
import struct
import sys

from PIL import Image

ROOT = __file__.replace("\\", "/").rsplit("/tools/", 1)[0]
ram = open(sys.argv[1], "rb").read()


def u32(a):
    return struct.unpack_from("<I", ram, a & 0xFFFFFF)[0]


def byte(a):
    return ram[(a & 0xFFFFFF) ^ 3]


# UIText_CharTable from the decomp: quoted characters and hex codes, in order.
src = open(ROOT + "/reference/pokemonsnap/src/window/text.c", encoding="utf-8").read()
body = src[src.index("UIText_CharTable[370] = {") :]
body = body[body.index("{") + 1 : body.index("};")]
table = [m.group(1) or m.group(2) for m in re.finditer(r"'((?:\\.|[^'])+)'|(0x[0-9A-Fa-f]+)", body)]
assert len(table) >= 340, len(table)

FULLWIDTH = {c: chr(ord(c) + 0xFEE0) for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!#$%&*()+=;:/.,?<>[]_@"}
FULLWIDTH.update({"'": "’", '"': "”", "-": "ー"})

glyphs12 = u32(0x8037EA6C)
atlas = Image.new("RGBA", (16 * 12, 6 * 12), (255, 255, 255, 0))
missing = []
for code in range(32, 128):
    ch = chr(code)
    if ch == " ":
        continue
    want = FULLWIDTH.get(ch)
    if want is None or want not in table:
        missing.append(ch)
        continue
    base = glyphs12 + table.index(want) * 72
    cell = Image.new("RGBA", (12, 12), (255, 255, 255, 0))
    i = 0
    for y in range(12):
        for x in range(12):
            b = byte(base + i // 2)
            v = (b & 0xF) if (x & 1) == 0 else (b >> 4)
            if x & 1:
                i += 2
            if v:
                cell.putpixel((x, y), (255, 255, 255, min(255, v * 17)))
    atlas.paste(cell, (((code - 32) % 16) * 12, ((code - 32) // 16) * 12))
atlas.save(ROOT + "/gfx/font.png")

# Glyph widths (rightmost lit column + 1), for proportional spacing (source/ui/game_font.h).
widths = []
for code in range(32, 128):
    cx, cy = ((code - 32) % 16) * 12, ((code - 32) // 16) * 12
    w = 0
    for x in range(12):
        if any(atlas.getpixel((cx + x, cy + y))[3] for y in range(12)):
            w = x + 1
    widths.append(w if code != 32 else 4)
with open(ROOT + "/source/ui/game_font.h", "w") as f:
    nl = chr(10)
    f.write("// Generated by tools/make_font.py: the game's 12x12 UI font (gfx/font.png), glyph widths for" + nl)
    f.write("// ASCII 32-127 (the atlas is 16 cells across, 12x12 each)." + nl + "#pragma once" + nl + nl)
    f.write("static const unsigned char game_font_width[96] = {" + nl)
    for i in range(0, 96, 16):
        f.write("    " + ", ".join(str(w) for w in widths[i:i + 16]) + "," + nl)
    f.write("};" + nl)
print("gfx/font.png written; no glyph for:", "".join(missing))
