# "Double Take!!": the port's subtitle, under the Pokemon Snap logo on the banner (make_banner.py) and
# on the title screen (drawn by the renderer after the game's logo, n64_renderer.cpp).
# A strip of film with "DOUBLE TAKE!!" on it, the letters exposed twice: a red exposure ("Snap"'s
# red) a little off from the yellow one (the logo's "Pokemon" yellow, blue outline), as when a
# camera takes a second picture over the first - a double take.
# Outputs:
#   assets/banner/subtitle.png        1024x256, for the banner
#   gfx/subtitle_preview.png          the in-game texture, to look at
#   source/render/subtitle_rgba.h     256x64 RGBA8 texels for the renderer
import os
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 1024, 256
FONT = "C:/Windows/Fonts/ariblk.ttf"  # Arial Black
TEXT = "DOUBLE TAKE!!"

YELLOW = (255, 203, 5, 255)
YELLOW_DARK = (238, 160, 0, 255)
BLUE = (29, 63, 140, 255)
RED = (227, 53, 13, 255)
FILM = (24, 22, 26, 255)
HOLE = (214, 206, 190, 255)


def sheared_text(fill, outline, outline_w, size):
    """The words in Arial Black, slanted forward, with an outline."""
    font = ImageFont.truetype(FONT, size)
    l, t, r, b = font.getbbox(TEXT)
    pad = outline_w + 8
    im = Image.new("RGBA", (r - l + pad * 2 + 60, b - t + pad * 2), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.text((pad - l, pad - t), TEXT, font=font, fill=fill, stroke_width=outline_w, stroke_fill=outline)
    shear = 0.2
    return im.transform(im.size, Image.AFFINE, (1, shear, -shear * im.height * 0.5, 0, 1, 0), Image.BICUBIC)


def gradient_fill(mask_im, top, bottom):
    """Recolours the letters' face top to bottom (keeps alpha)."""
    w, h = mask_im.size
    grad = Image.new("RGBA", (w, h))
    gd = ImageDraw.Draw(grad)
    for y in range(h):
        t = y / max(1, h - 1)
        gd.line([(0, y), (w, y)], fill=tuple(int(top[i] + (bottom[i] - top[i]) * t) for i in range(3)) + (255,))
    grad.putalpha(mask_im.getchannel("A"))
    return grad


def build():
    canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))

    # The film: a band with sprocket holes along both edges, its ends cut at a slant.
    film = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    fd = ImageDraw.Draw(film)
    top, bottom = 40, 216
    fd.polygon([(40, top), (W - 20, top), (W - 40, bottom), (20, bottom)], fill=FILM)
    for x in range(64, W - 60, 46):
        fd.rounded_rectangle([x, top + 12, x + 24, top + 32], radius=5, fill=HOLE)
        fd.rounded_rectangle([x - 8, bottom - 32, x + 16, bottom - 12], radius=5, fill=HOLE)
    # A thin frame line inside, where one exposure ends and the next begins.
    fd.line([(60, top + 42), (W - 44, top + 42)], fill=(70, 66, 72, 255), width=3)
    fd.line([(48, bottom - 42), (W - 56, bottom - 42)], fill=(70, 66, 72, 255), width=3)
    shadow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    shadow.putalpha(film.getchannel("A").point(lambda v: v * 0.5))
    canvas.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(8)), (6, 10))
    canvas.alpha_composite(film)

    # The letters, exposed twice.
    size = 84
    # Face: gradient letters over their own blue outline.
    outline = sheared_text(BLUE, BLUE, 8, size)
    letters = gradient_fill(sheared_text(YELLOW, YELLOW, 0, size), (255, 226, 70), YELLOW_DARK)
    face = sheared_text((250, 246, 236, 255), (250, 246, 236, 255), 12, size)  # a light edge: readable on film
    face.alpha_composite(outline)
    face.alpha_composite(letters)
    ghost = sheared_text(RED, RED, 12, size)
    ghost.putalpha(ghost.getchannel("A").point(lambda v: v * 0.62))
    l, t, r, b = face.getbbox()  # centred on what's drawn (the slant leaves room on one side)
    tx = (W - (r - l)) // 2 - l
    ty = (H - (b - t)) // 2 - t
    canvas.alpha_composite(ghost, (tx + 13, ty - 7))
    canvas.alpha_composite(face, (tx, ty))
    # A flash glint on the first letter.
    glint = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    gd = ImageDraw.Draw(glint)
    cx, cy = tx + l + 52, ty + t + 22
    for r, a in ((26, 70), (14, 140), (6, 255)):
        gd.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(255, 255, 255, a))
    gd.polygon([(cx - 44, cy), (cx, cy - 3), (cx + 44, cy), (cx, cy + 3)], fill=(255, 255, 255, 220))
    gd.polygon([(cx, cy - 30), (cx + 3, cy), (cx, cy + 30), (cx - 3, cy)], fill=(255, 255, 255, 220))
    canvas.alpha_composite(glint.filter(ImageFilter.GaussianBlur(1)))
    return canvas


def main():
    art = build()
    art.save(os.path.join(ROOT, "assets/banner/subtitle.png"))
    tex = art.resize((256, 64), Image.LANCZOS)
    tex.save(os.path.join(ROOT, "gfx/subtitle_preview.png"))
    px = tex.load()
    lines = [
        "// Generated by tools/make_subtitle.py: the \"Double Take!!\" subtitle, 256x64 RGBA8 (0xRRGGBBAA),",
        "// rows top to bottom.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "constexpr int subtitle_w = 256, subtitle_h = 64;",
        "static const uint32_t subtitle_rgba[subtitle_w * subtitle_h] = {",
    ]
    for y in range(64):
        row = []
        for x in range(256):
            r, g, b, a = px[x, y]
            if a == 0:
                r = g = b = 0
            row.append("0x%02X%02X%02X%02Xu" % (r, g, b, a))
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    with open(os.path.join(ROOT, "source/render/subtitle_rgba.h"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("subtitle written")


if __name__ == "__main__":
    main()
